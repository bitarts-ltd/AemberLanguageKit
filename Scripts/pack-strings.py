#!/usr/bin/env python3
"""Keeps a language pack's user-visible text and its translations.

A pack is one file and can't carry .lproj folders, so its text is
LocalizedText values in Swift. Each pack keeps its strings in its own
string catalog, Packs/<Name>/Strings.xcstrings (the same format as
Xcode's), which is the source of truth for its translations; this
script turns it into Swift and checks it.

Commands:

  seed CATALOG FROM KEY... [--from-file KEYS]
      Adds keys to a pack's catalog, copying each one's comment and
      translations from another catalog (Aember's
      Localizable.xcstrings, when a pack takes over code that was
      Aember's). Keys already in the pack's catalog keep theirs. A key
      FROM doesn't have is added untranslated.

  generate CATALOG OUTPUT [--type NAME]
      Writes a Swift file defining `enum NAME` (PackStrings by
      default) with a LocalizedText for every key, and
      `NAME.text(_:)`, which a pack calls with the English text:
          PackStrings.text("Swift Package Manager").localized
      A key the catalog doesn't have comes back as English only.

  check CATALOG SOURCES... [--languages de,es,...]
      Fails when the Swift sources use PackStrings.text("...") with a
      key the catalog doesn't have, or a key lacks a translation into
      one of the languages (de, es, fr, it, ja and ru by default, as
      Aember ships).

Plural variations aren't supported: a pack words counts without them,
or keeps such text in Aember.
"""

import argparse
import json
import os
import re
import sys

DEFAULT_LANGUAGES = ["de", "es", "fr", "it", "ja", "ru"]
USE_PATTERN = re.compile(r'\b(?P<type>[A-Za-z_][A-Za-z0-9_]*)\.text\(\s*"((?:\\.|[^"\\])*)"\s*\)')


def load(path):
    """Reads a catalog, or an empty one when the file doesn't exist."""
    if not os.path.exists(path):
        return {"sourceLanguage": "en", "strings": {}, "version": "1.0"}
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def save(path, catalog):
    """Writes a catalog as Xcode does: sorted keys, two-space indent."""
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(catalog, handle, ensure_ascii=False, indent=2, sort_keys=True, separators=(",", " : "))
        handle.write("\n")


def translations(entry):
    """The plain translations of a catalog entry, by language."""
    result = {}
    for language, localization in (entry.get("localizations") or {}).items():
        unit = localization.get("stringUnit")
        if unit and unit.get("value") is not None:
            result[language] = unit["value"]
    return result


def swift_string(text):
    """Text as a Swift string literal."""
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    return '"' + escaped + '"'


def unescape_swift(text):
    """A Swift string literal's contents as the text it means."""
    return re.sub(r'\\(.)', lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), text)


def seed(args):
    pack = load(args.catalog)
    source = load(args.source)
    keys = list(args.keys)
    if args.from_file:
        with open(args.from_file, encoding="utf-8") as handle:
            keys += [line.rstrip("\n") for line in handle if line.strip()]
    added = missing = 0
    for key in keys:
        if key in pack["strings"]:
            continue
        entry = source["strings"].get(key)
        if entry is None:
            pack["strings"][key] = {}
            missing += 1
        else:
            copy = {k: v for k, v in entry.items() if k in ("comment", "localizations")}
            pack["strings"][key] = copy
        added += 1
    save(args.catalog, pack)
    print(f"{added} keys added, {missing} of them untranslated")
    return 0


def generate(args):
    catalog = load(args.catalog)
    name = args.type
    lines = [
        "// Generated by AemberLanguageKit's Scripts/pack-strings.py from",
        f"// {os.path.basename(args.catalog)}. Don't edit; edit the catalog and",
        "// generate again.",
        "",
        "import AemberLanguageKit",
        "",
        "/// @brief The pack's user-visible text, with its translations",
        f"enum {name} {{",
        "",
        "    /// Every key's text, by its English text",
        "    static let table: [String: LocalizedText] = [",
    ]
    for key in sorted(catalog["strings"]):
        found = translations(catalog["strings"][key])
        pairs = ", ".join(f"{swift_string(lang)}: {swift_string(value)}" for lang, value in sorted(found.items()) if lang != "en")
        lines.append(f"        {swift_string(key)}: LocalizedText({swift_string(key)}, translations: [{pairs or ':'}]),")
    lines += [
        "    ]",
        "",
        "    /// @brief A text and its translations.",
        "    /// @param english The English text, the catalog's key",
        "    /// @return The text; English only when the catalog lacks it",
        "    static func text(_ english: String) -> LocalizedText {",
        "        table[english] ?? LocalizedText(english)",
        "    }",
        "}",
        "",
    ]
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print(f"{len(catalog['strings'])} strings written to {args.output}")
    return 0


def check(args):
    catalog = load(args.catalog)
    languages = args.languages.split(",") if args.languages else DEFAULT_LANGUAGES
    problems = []
    used = set()
    for path in args.sources:
        files = [path]
        if os.path.isdir(path):
            files = [os.path.join(root, f) for root, _, names in os.walk(path) for f in names if f.endswith(".swift")]
        for file in files:
            with open(file, encoding="utf-8") as handle:
                for match in USE_PATTERN.finditer(handle.read()):
                    if match.group("type") == args.type:
                        used.add(unescape_swift(match.group(2)))
    for key in sorted(used):
        if key not in catalog["strings"]:
            problems.append(f"not in the catalog: {key!r}")
    for key, entry in sorted(catalog["strings"].items()):
        found = translations(entry)
        lacking = [lang for lang in languages if lang not in found]
        if lacking:
            problems.append(f"untranslated into {','.join(lacking)}: {key!r}")
    for line in problems:
        print(line)
    print(f"{len(used)} keys used, {len(catalog['strings'])} in the catalog, {len(problems)} problems")
    return 1 if problems else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    commands = parser.add_subparsers(dest="command", required=True)
    p = commands.add_parser("seed")
    p.add_argument("catalog")
    p.add_argument("source")
    p.add_argument("keys", nargs="*")
    p.add_argument("--from-file")
    p.set_defaults(run=seed)
    p = commands.add_parser("generate")
    p.add_argument("catalog")
    p.add_argument("output")
    p.add_argument("--type", default="PackStrings")
    p.set_defaults(run=generate)
    p = commands.add_parser("check")
    p.add_argument("catalog")
    p.add_argument("sources", nargs="+")
    p.add_argument("--type", default="PackStrings")
    p.add_argument("--languages")
    p.set_defaults(run=check)
    args = parser.parse_args()
    return args.run(args)


if __name__ == "__main__":
    sys.exit(main())
