#!/usr/bin/env python3
"""Embeds a pack's tree-sitter queries in Swift.

A pack is one file, so its queries are compiled in as strings. This
reads the .scm files in a pack's Queries folder (highlights.scm,
injections.scm, locals.scm, folds.scm; any missing is nil) and writes
a Swift file defining

    enum PackQueries {
        static let queries: LanguageQueries
    }

for the pack's LanguageDefinition. A pack with several languages keeps
each one's queries in a folder of its own (Queries/javascript/,
Queries/typescript/), and gets a LanguageQueries per folder, named for
it (PackQueries.javascript). Run it again after updating a
query, and commit what it writes.

Usage: embed-queries.py QUERIES_DIR OUTPUT [--type NAME]
"""

import argparse
import os
import sys

KINDS = ["highlights", "injections", "locals", "folds"]


def literal(text):
    """Text as a Swift raw multi-line string literal."""
    hashes = "#"
    while ('"""' + hashes) in text:
        hashes += "#"
    return f'{hashes}"""\n{text.rstrip(chr(10))}\n"""{hashes}'


def queries_in(folder):
    """The .scm files in a folder, by kind."""
    found = {}
    for kind in KINDS:
        path = os.path.join(folder, kind + ".scm")
        if os.path.exists(path):
            with open(path, encoding="utf-8") as handle:
                found[kind] = handle.read()
    return found


def declaration(name, found):
    """A LanguageQueries constant."""
    arguments = ",\n".join(f"        {kind}: {literal(found[kind])}" for kind in KINDS if kind in found)
    return f"    static let {name} = LanguageQueries(\n{arguments}\n    )"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("queries")
    parser.add_argument("output")
    parser.add_argument("--type", default="PackQueries")
    args = parser.parse_args()
    sets = {}
    own = queries_in(args.queries)
    if own:
        sets["queries"] = own
    for entry in sorted(os.listdir(args.queries)):
        folder = os.path.join(args.queries, entry)
        if os.path.isdir(folder) and queries_in(folder):
            sets[entry] = queries_in(folder)
    if not sets:
        print(f"no queries in {args.queries}", file=sys.stderr)
        return 1
    lines = [
        "// Generated by AemberLanguageKit's Scripts/embed-queries.py from the",
        "// pack's Queries folder. Don't edit; edit the .scm files and generate",
        "// again.",
        "",
        "import AemberLanguageKit",
        "",
        "/// @brief The pack's tree-sitter queries",
        f"enum {args.type} {{",
        "",
    ]
    lines.append("\n\n".join(f"    /// The queries for {name}\n" + declaration(name, found) for name, found in sets.items()))
    lines += ["}", ""]
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print(f"{', '.join(sets)} written to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
